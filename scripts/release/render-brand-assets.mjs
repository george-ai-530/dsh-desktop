import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

// Render the tracked SVG brand sources into the tracked brand assets:
//
//   build/brand/app-icon.svg      -> build/app-icon.png  (1024x1024)
//                                 -> build/icon.png      (1254x1254, upstream
//                                    favicon/manifest contract kept at the legacy
//                                    dimension by install-brand-assets.mjs)
//   build/brand/logo-wordmark.svg -> build/logo-light.png / logo-dark.png (336x192)
//   build/brand/brand-mark.svg    -> build/startup-brand.svg (the splash/boot-cover
//                                    startup image; colored, cropped to the
//                                    mark's tight bounds)
//
// The dark wordmark variant substitutes the brand blue for the lighter
// #366EF4 so the lockup keeps contrast on dark backgrounds; the orange part
// is unchanged. startup-brand.svg is only written when absent: drop an
// official logo SVG in its place and regeneration leaves it alone (delete the
// file to go back to the generated default). Run via `npm run brand:render`.
// sharp arrives via the upstream dependency closure, same access pattern as
// the other release scripts.

const require = createRequire(import.meta.url)
const sharp = require('sharp')

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const buildDirectory = path.join(projectRoot, 'build')

const brandDirectory = path.join(buildDirectory, 'brand')
const appIconSvg = path.join(brandDirectory, 'app-icon.svg')
const wordmarkSvg = path.join(brandDirectory, 'logo-wordmark.svg')
const brandMarkSvg = path.join(brandDirectory, 'brand-mark.svg')
const startupDestination = path.join(buildDirectory, 'startup-brand.svg')

const BRAND_BLUE = '#0052D9'
const BRAND_BLUE_DARK = '#366EF4'
const BRAND_ORANGE = '#E37318'

// App-icon canvas is 1024; rasterize at a higher density for the 1254px
// favicon target so the vector is sampled once at native size instead of
// being upscaled from 1024.
const renderSvg = async (svgPath, size, destination) => {
  const density = Math.max(72, Math.ceil((96 * size) / 1024))
  await sharp(svgPath, { density })
    .resize(size, size)
    .png()
    .toFile(destination)
}

await renderSvg(appIconSvg, 1024, path.join(buildDirectory, 'app-icon.png'))
await renderSvg(appIconSvg, 1254, path.join(buildDirectory, 'icon.png'))

const wordmarkSource = await readFile(wordmarkSvg, 'utf8')
if (!wordmarkSource.includes(BRAND_BLUE)) {
  throw new Error(`${path.relative(projectRoot, wordmarkSvg)} does not contain ${BRAND_BLUE}; regenerate it with scripts/release/outline-wordmark.mjs`)
}
const wordmarkDark = wordmarkSource.replaceAll(BRAND_BLUE, BRAND_BLUE_DARK)

const WORDMARK_WIDTH = 336
const WORDMARK_HEIGHT = 192
const renderWordmark = async (svgText, destination) => {
  await sharp(Buffer.from(svgText), { density: 288 })
    .resize(WORDMARK_WIDTH, WORDMARK_HEIGHT, {
      // The lockup is much wider than the legacy 336x192 canvas; contain it
      // on a transparent canvas instead of cropping the mark.
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 }
    })
    .png()
    .toFile(destination)
}

await renderWordmark(wordmarkSource, path.join(buildDirectory, 'logo-light.png'))
await renderWordmark(wordmarkDark, path.join(buildDirectory, 'logo-dark.png'))

// Startup image: the brand mark in brand blue, cropped to its tight bounds
// (parsed from the SVG so an official mark replacement flows through). A
// 640x536 canvas matches the aspect consumed by the splash page and boot
// cover. An official startup-brand.svg dropped into build/ is never
// overwritten.
const startupExists = await readFile(startupDestination, 'utf8').then(
  () => true,
  () => false
)
if (startupExists) {
  console.log('Kept existing build/startup-brand.svg (delete it to regenerate the default)')
} else {
  const markSvg = await readFile(brandMarkSvg, 'utf8')
  const markPathData = /<path[^>]*\sd="([^"]+)"/u.exec(markSvg)?.[1]
  if (!markPathData) throw new Error('brand-mark.svg: no path data found')
  const bounds = /x\s+([\d.]+)\s+y\s+([\d.]+)\s+w\s+([\d.]+)\s+h\s+([\d.]+)/.exec(markSvg)
  if (!bounds) throw new Error('brand-mark.svg: tight-bounds comment (x … y … w … h …) missing')
  const width = Math.round(Number(bounds[3]))
  const height = Math.round(Number(bounds[4]))
  const startupSvg = `<svg width="${width}" height="${height}" viewBox="${bounds[1]} ${bounds[2]} ${bounds[3]} ${bounds[4]}" fill="none" xmlns="http://www.w3.org/2000/svg">
<!-- Generated by scripts/release/render-brand-assets.mjs from build/brand/brand-mark.svg.
     Replace this file with an official logo SVG to rebrand the startup page;
     regeneration skips existing files. -->
<path fill="${BRAND_BLUE}" d="${markPathData}"/>
</svg>
`
  await writeFile(startupDestination, startupSvg)
  console.log(`Rendered build/startup-brand.svg (${width}x${height} default)`)
}

console.log('Rendered build/app-icon.png, build/icon.png, build/logo-light.png, build/logo-dark.png')
